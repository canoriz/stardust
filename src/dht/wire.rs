use super::*;
use bt_bencode::ByteString;
use serde::{Deserialize, Serialize};

fn empty_bytestring() -> ByteString {
    ByteString::from("")
}

#[derive(PartialEq, Debug, Serialize, Deserialize)]
pub struct WireKRPC {
    /// transaction ID
    t: ByteString, // TODO: maybe use [u8;2] spec says 2 should be OK

    /// client version
    #[serde(default = "empty_bytestring")]
    v: ByteString, // TODO: maybe use [u8;4] spec says 4 is enough

    /// type 'q' 'r' or 'e'
    /// 'q': query
    /// 'r': response
    /// 'e': error
    #[serde(with = "serde_bytes")]
    y: [u8; 1],

    /// if y == "q"
    #[serde(skip_serializing_if = "Option::is_none")]
    q: Option<ByteString>,

    /// if y == "q"
    #[serde(skip_serializing_if = "Option::is_none")]
    a: Option<BtValue>,

    /// if y == "r"
    #[serde(skip_serializing_if = "Option::is_none")]
    r: Option<Resp>,

    /// if y == "e"
    #[serde(skip_serializing_if = "Vec::is_empty")]
    #[serde(default)]
    e: Vec<(u32, String)>,
}

impl From<KRPC> for WireKRPC {
    fn from(krpc: KRPC) -> Self {
        match krpc.inner {
            KRPCInner::Request(arg) => {
                let (q, bv) = match arg {
                    Arg::Ping(a) => {
                        let bv = bt_bencode::to_value(&a).unwrap();
                        ("ping", bv)
                    }
                    Arg::FindNode(a) => {
                        let bv = bt_bencode::to_value(&a).unwrap();
                        ("find_node", bv)
                    }
                    Arg::AnnouncePeer(a) => {
                        let bv = bt_bencode::to_value(&a).unwrap();
                        ("announce_peer", bv)
                    }
                    Arg::GetPeers(a) => {
                        let bv = bt_bencode::to_value(&a).unwrap();
                        ("get_peers", bv)
                    }
                };
                Self {
                    t: krpc.t,
                    v: krpc.v,
                    y: [b'q'],
                    q: Some(q.into()),
                    a: Some(bv),
                    r: None,
                    e: vec![],
                }
            }
            KRPCInner::Response(resp) => Self {
                t: krpc.t,
                v: krpc.v,
                y: [b'r'],
                q: None,
                a: None,
                r: Some(resp),
                e: vec![],
            },
            KRPCInner::Err(e) => Self {
                t: krpc.t,
                v: krpc.v,
                y: [b'e'],
                q: None,
                a: None,
                r: None,
                e: e,
            },
        }
    }
}

impl TryFrom<WireKRPC> for KRPC {
    type Error = &'static str;
    fn try_from(w: WireKRPC) -> Result<Self, Self::Error> {
        match w.y.as_ref() {
            [b'q'] => {
                let query = if let Some(x) = w.q {
                    x
                } else {
                    return Err("type q, no q field");
                };
                let a = if let Some(a) = w.a {
                    a
                } else {
                    return Err("type q, no a field");
                };

                const PING: &[u8] = "ping".as_bytes();
                const FIND_NODE: &[u8] = "find_node".as_bytes();
                const GET_PEERS: &[u8] = "get_peers".as_bytes();
                const ANNOUNCE_PEER: &[u8] = "announce_peer".as_bytes();
                match query.as_ref() {
                    PING => {
                        let p: PingArg = bt_bencode::from_value(a)
                            .map_err(|_| r#"fail to bdecode "a" to ping"#)?;
                        Ok(KRPC {
                            t: w.t,
                            v: w.v,
                            inner: KRPCInner::Request(Arg::Ping(p)),
                        })
                    }
                    FIND_NODE => {
                        let f: FindNodeArg = bt_bencode::from_value(a)
                            .map_err(|_| r#"fail to bdecode "a" to find_node "#)?;
                        Ok(KRPC {
                            t: w.t,
                            v: w.v,
                            inner: KRPCInner::Request(Arg::FindNode(f)),
                        })
                    }
                    GET_PEERS => {
                        let g: GetPeersArg = bt_bencode::from_value(a)
                            .map_err(|_| r#"fail to bdecode "a" to get_peers"#)?;
                        Ok(KRPC {
                            t: w.t,
                            v: w.v,
                            inner: KRPCInner::Request(Arg::GetPeers(g)),
                        })
                    }
                    ANNOUNCE_PEER => {
                        let ap: AnnouncePeerArg = bt_bencode::from_value(a)
                            .map_err(|_| r#"fail to bdecode "a" to announce_peer"#)?;
                        Ok(KRPC {
                            t: w.t,
                            v: w.v,
                            inner: KRPCInner::Request(Arg::AnnouncePeer(ap)),
                        })
                    }
                    _ => Err("unknown query"),
                }
            }
            [b'r'] => {
                let r = w.r.ok_or("no r field")?;
                Ok(KRPC {
                    t: w.t,
                    v: w.v,
                    inner: KRPCInner::Response(Resp {
                        id: r.id,
                        nodes: r.nodes,
                        nodes6: r.nodes6,
                        token: r.token,
                        values: r.values,
                    }),
                })
            }
            [b'e'] => Ok(KRPC {
                t: w.t,
                v: w.v,
                inner: KRPCInner::Err(w.e),
            }),
            _ => Err("unknown type"),
        }
    }
}

